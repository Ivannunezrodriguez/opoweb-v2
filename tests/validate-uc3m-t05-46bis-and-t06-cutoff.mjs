import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const dir='content/uc3m/';
const manual=readFileSync(dir+'tema-05/manual.md','utf8');
const sources=readFileSync(dir+'tema-05/fuentes.md','utf8');
const bank=JSON.parse(readFileSync(dir+'tema-05/preguntas.json','utf8')).preguntas;
const q=bank.find(x=>x.id==='UC3M-T05-010');
assert(q, 'Question T05-010 missing');
assert.equal(q.correcta,3);
assert.equal(q.opciones[q.correcta],q.respuestaLiteral);
assert(q.pregunta.includes('censo electoral')&&q.pregunta.includes('padrones municipales')&&q.pregunta.includes('Sistema Nacional de Salud'),'Incorrect broad data-systems premise');
assert(q.justificacion.includes('No lo establece indiscriminadamente'),'Scope warning lost in question');
assert(manual.includes('otros registros de población')&&manual.includes('datos fiscales')&&manual.includes('Sistema Nacional de Salud'),'Missing 46bis enumerated categories');
assert(manual.includes('No es correcto convertir el artículo 46 bis'),'Overgeneralization warning lost');
assert(!manual.includes('Los sistemas con datos especialmente protegidos deben ubicarse, con carácter general'),'Legacy wrong rule remains');
assert(sources.includes('decisión de adecuación')&&sources.includes('obligaciones internacionales'),'Transfer exception incomplete');
const t6=readFileSync(dir+'tema-06/fuentes.md','utf8');
assert(t6.includes('listas definitivas')&&t6.includes('No')&&t6.includes('fecha de realización'),'T6 official date-cut missing');
